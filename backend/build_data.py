"""Regenerates ../data.js (static/offline fallback) from the CSVs. Run after editing a CSV:  python backend/build_data.py"""
import json
from pathlib import Path
import core

inv = []
for _, r in core.INV.iterrows():
    inv.append(dict(id=r['id'], name=r['name'], platform=r['platform'], category=r['category'],
                    rel=dict(iss=int(r['rel_iss']), lunar=int(r['rel_lunar']), mars=int(r['rel_mars']), rover=int(r['rel_rover'])),
                    goals=r['goals'], o2=bool(r['o2']), keys=r['keys'], topics=r['topics'], summary=r['summary'], insight=r['insight'],
                    earth=r['earth'], url=r['url'], cite=r['cite'], sources=r['source_ids'], basis=r['basis']))
data = dict(investigations=inv, habitats=core.HABITATS, goals=core.GOALS,
            sources={r['id']: dict(intext=r['intext'], url=r['url'], ref_html=r['ref_html'], ref_text=r['ref_text'], verified=bool(r['verified'])) for _, r in core.SRC.iterrows()},
            references=core.SRC['id'].tolist())
js = ('/* AUTO-GENERATED by backend/build_data.py from investigations.csv + sources.csv. Do not edit by hand.\n'
      '   rel (1-5), goals and o2 are TEAM-ASSIGNED editorial weights, not NASA values. */\n'
      'window.VELTRIXA_DATA = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
Path(__file__).resolve().parent.parent.joinpath('data.js').write_text(js, encoding='utf-8')
print('data.js written:', len(inv), 'investigations,', len(data['sources']), 'sources')
